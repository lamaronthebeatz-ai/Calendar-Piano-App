"""Build the Grove part of "Từ điển âm nhạc Lamar" (/terms).

Input: scripts/grove/entries-<vol>.json.gz, the entries parse.py split from the five volumes of Grove's Dictionary of
Music and Musicians, 2nd ed. (ed. J. A. Fuller Maitland, New York: Macmillan, 1904–1910; public domain; Cornell
scans on the Internet Archive, ids below), and the Vietnamese entries written for the app in scripts/grove/vi/*.json
({id: {title, kind?, vi}}).
Output (generated by `npm run build`/`dev`, not committed): public/grove/<letter><n>.json (entries with the
Vietnamese text and the original English, fetched when an entry is opened) and src/features/terms/grove-index.json (headwords, volume, page, Vietnamese titles and first sentences).

Usage: python3 scripts/grove/build.py   (npm run grove)
"""
import gzip, json, re, unicodedata, glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# volume: (Internet Archive id, letters, year of the volume)
VOLUMES = {
    1: ('cu31924021782838', 'abcde', 1904),
    2: ('cu31924021782846', 'fghijkl', 1906),
    3: ('cu31924021782853', 'mnop', 1907),
    4: ('cu31924021782861', 'qrs', 1908),
    5: ('cu31924021782879', 'tuvwxyz', 1910),
}
# vol. V ends with an Appendix of additions to all five volumes, A to Z (from p. 605)
APPENDIX = (5, 605)

vi = {}
for f in sorted(glob.glob(f'{ROOT}/scripts/grove/vi/*.json')):
    vi.update(json.load(open(f)))

def slug(s):
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')

def kind(e):
    t = e['text'][:260]
    if re.search(r'\b(born|bom|bora|died|baptized|flourished|fl\.)\b', t) or re.search(r'\(\d{4}', t): return 'person'
    if re.search(r'\b(opera|oratorio|cantata|operetta|ballet|tragedie|comic opera|libretto)\b', t[:120], re.I): return 'work'
    if re.search(r'\b(society|festival|academy|conservatoire|conservatorium|school|college|club|union|institution)\b', t[:100], re.I): return 'institution'
    return 'term'

def letters_of(entries, allowed):
    """The letter of each entry: the majority of the headwords around it, never going back (OCR headings such as
    'OBCHESTBAL OVBETUBES' inside an M article must not switch the shard to O)."""
    firsts = [e['head'][0].lower() for e in entries]
    out, cur = [], allowed[0]
    for i in range(len(entries)):
        win = [c for c in firsts[max(0, i - 6):i + 7] if c in allowed]
        l = max(set(win), key=win.count) if win else cur
        if l > cur: cur = l
        out.append(cur)
    return out

seen = set()
index, shards = [], {}
for vol, (ia, allowed, year) in VOLUMES.items():
    entries = json.load(gzip.open(f'{ROOT}/scripts/grove/entries-{vol}.json.gz'))
    main = [e for e in entries if not (vol == APPENDIX[0] and e['page'] >= APPENDIX[1])]
    app = entries[len(main):]
    letters = letters_of(main, allowed) + [e['head'][0].lower() if e['head'][0].isalpha() else 'a' for e in app]
    for n, (e, shard) in enumerate(zip(entries, letters)):
        base = f"{slug(e['head'])}-{vol}-{e['page']}"
        eid, k2 = base, 2
        while eid in seen:
            eid, k2 = f'{base}-{k2}', k2 + 1
        seen.add(eid)
        v = vi.get(eid, {})
        k = v.get('kind') or kind(e)
        item = {'id': eid, 'head': e['head'], 'vol': vol, 'page': e['page'], 'leaf': e['leaf'], 'kind': k, 'words': e['words']}
        if n >= len(main): item['app'] = 1
        if v:
            item['title'] = v['title']
            item['vi'] = v['vi']
        shards.setdefault(shard, []).append({**item, 'en': e['text']})
        gist = re.split(r'(?<=[.!?])\s', v['vi'].replace('*', '').strip(), maxsplit=1)[0][:220] if v else ''
        index.append({'id': eid, 'h': e['head'], 'v': vol, 'p': e['page'], 's': shard, 'k': k,
                      **({'a': 1} if n >= len(main) else {}), **({'t': v['title'], 'g': gist} if v else {})})

# a letter is fetched in pieces of about CHUNK entries (S alone is 3 MB of English) — the index names the piece
CHUNK = 80
for letter in list(shards):
    items = shards.pop(letter)
    for k in range(0, len(items), CHUNK):
        shards[f'{letter}{k // CHUNK + 1}'] = items[k:k + CHUNK]
piece = {it['id']: s for s, items in shards.items() for it in items}
for h in index:
    h['s'] = piece[h['id']]

os.makedirs(f'{ROOT}/public/grove', exist_ok=True)
for f in glob.glob(f'{ROOT}/public/grove/*.json'):
    os.remove(f)
for s, items in shards.items():
    json.dump(items, open(f'{ROOT}/public/grove/{s}.json', 'w'), ensure_ascii=False, separators=(',', ':'))
json.dump(index, open(f'{ROOT}/src/features/terms/grove-index.json', 'w'), ensure_ascii=False, separators=(',', ':'))
missing = [k for k in vi if k not in seen]
print(len(index), 'entries,', sum(1 for i in index if 't' in i), 'with Vietnamese;',
      len(shards), 'pieces', '; unknown vi ids:', missing[:8], len(missing))
